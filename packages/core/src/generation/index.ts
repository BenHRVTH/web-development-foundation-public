import { createHash } from 'node:crypto';
import { type Result } from '../diagnostics.ts';
import { resolveTokens } from '../tokens/resolve.ts';
import { cssVariableName, cssValue, generateTokenCss } from '../tokens/css.ts';
export { cssVariableName, cssValue } from '../tokens/css.ts';
/** ASCII ordering, recursively sorted object keys; arrays retain declared order. */
export function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value !== null && typeof value === 'object')
    return `{${Object.entries(value)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([k, v]) => `${JSON.stringify(k)}:${canonicalJson(v)}`)
      .join(',')}}`;
  return JSON.stringify(value) ?? 'null';
}
export interface GeneratedArtifacts {
  css: string;
  typescript: string;
  sourceDigest: string;
}
export function generateTokens(input: unknown): Result<GeneratedArtifacts> {
  const result = resolveTokens(input);
  if (!result.ok) return result;
  const resolved = result.value;
  const ids = Object.keys(resolved.base);
  const cssResult = generateTokenCss(input);
  if (!cssResult.ok) return cssResult;
  const sourceDigest = createHash('sha256')
    .update(canonicalJson(resolved.config))
    .digest('hex');
  const header = `/* Generated by WDF M1. DO NOT EDIT. Source SHA-256: ${sourceDigest} */\n`;
  const css = header + cssResult.value;
  const values = Object.fromEntries(
    Object.entries(resolved.base).map(([id, token]) => [id, cssValue(token)]),
  );
  const cssVariables = Object.fromEntries(
    ids.map((id) => [id, cssVariableName(id)]),
  );
  const responsiveValues = Object.fromEntries(
    resolved.responsive.map((r) => [
      r.name,
      {
        minWidth: r.minWidth,
        values: Object.fromEntries(
          Object.entries(r.tokens).map(([id, t]) => [id, cssValue(t)]),
        ),
      },
    ]),
  );
  const typescript = `${header}export const tokenValues = ${JSON.stringify(values, null, 2)} as const;\nexport type TokenId = keyof typeof tokenValues;\nexport const cssVariables = ${JSON.stringify(cssVariables, null, 2)} as const;\nexport type CssVariable = (typeof cssVariables)[TokenId];\nexport const responsiveTokenValues = ${JSON.stringify(responsiveValues, null, 2)} as const;\n`;
  return { ok: true, value: { css, typescript, sourceDigest } };
}
